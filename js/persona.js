  // 情绪保护：当状态差时关闭毒舌，进入温和关心模式
  softMode() {
    const d = Store.get();
    const s = d.state;
    const lowEnergy = s && (s.energy === 'tired' || s.energy === 'wiped');
    const badSleep = s && (s.sleep === 'bad');
    const pain = s && (s.ache && s.ache !== 'none');
    return !!(lowEnergy || badSleep || pain);
  },

  // 读取场景文案：状态差强制温和（禁止毒舌），否则按比例系统/妍宝
  get(pool, force) {
    const p = this.pools;
    const sys = p[pool + '_sys'];
    const yan = p[pool + '_yan'];
    if (!sys && !yan) return '';
    if (!force && this.softMode()) {
      // 温和模式覆盖，且允许妍宝出现
      return this._pick(p.gentle_sys, p.gentle_yan, true);
    }
    return this._pick(sys, yan);
  },

  // 连续训练里程碑文案
  _milestone(streak) {
    if (streak >= 30) return this._pick(this.pools.streak30_sys, this.pools.streak30_yan);
    if (streak >= 10) return this._pick(this.pools.streak10_sys, this.pools.streak10_yan);
    if (streak >= 7) return this._pick(this.pools.streak7_sys, this.pools.streak7_yan);
    return this._pick(this.pools.streak3_sys, this.pools.streak3_yan);
  },

  // 训练前温馨文案（独立池，用于开工前）
  preWarm(force) {
    return this._pick(this.pools.preWarm_sys, this.pools.preWarm_yan, force);
  },

  // 状态差时的温和关心（强制妍宝温和）
  gentle(force) {
    return this._pick(this.pools.gentle_sys, this.pools.gentle_yan, force || true);
  },

  fromYan() {
    const p = this.pools.yanMessages;
    return p[Math.floor(Math.random() * p.length)];
  },

  // 第一版：特定场景妍宝文案（低频出现，仅一次）
  special(key) {
    const S = {
      mingActivated: '这一周已经给你安排好了。你按自己的状态认真练就行。别乱加重量。',
      smartReady: '新计划可以试试。先练几次，再看身体反馈。'
    };
    return S[key] || '';
  },

  homeQuote() {
    const p = this.pools.homeQuote;
    return p[Math.floor(Math.random() * p.length)];
  },

  reminder() {
    return this._pick(this.pools.reminder_sys, this.pools.reminder_yan);
  },

  // SMART COACH：按场景池取妍宝一句（care 场景强制温和，禁止毒舌）
  coach(pool, forceYan) {
    const p = this.pools;
    const sys = p[pool + '_sys'];
    const yan = p[pool + '_yan'];
    if (!sys && !yan) return '';
    // forceYan === 'sys'：强制系统直说池（TODAY REVIEW 等"一个状态一个结论"场景）
    if (forceYan === 'sys') return sys[Math.floor(Math.random() * sys.length)];
    // care 场景：软模式覆盖逻辑已在调用侧处理，这里直接按池挑
    return this._pick(sys, yan, forceYan);
  }
